package dev.codewitness.support.dependency;

import dev.codewitness.core.model.PackageCoordinate;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Reading resolved versions out of a {@code [[package]]} lock file, for Cargo and Poetry. */
class TomlPackageTableTest {

    @Test
    @DisplayName("every [[package]] table with a name and a version becomes a coordinate")
    void readsCargoLock() {
        String lock = """
                # This file is automatically @generated by Cargo.
                version = 3

                [[package]]
                name = "sample"
                version = "0.1.0"
                dependencies = [
                 "serde",
                ]

                [[package]]
                name = "serde"
                version = "1.0.193"
                source = "registry+https://github.com/rust-lang/crates.io-index"
                checksum = "deadbeef"

                [[patch.unused]]
                name = "ignored"
                version = "9.9.9"
                """;

        List<PackageCoordinate> coordinates = TomlPackageTable.parse(lock, PackageCoordinate.CRATES_IO);

        assertEquals(List.of("sample@0.1.0", "serde@1.0.193"),
                coordinates.stream().map(PackageCoordinate::display).toList());
        assertEquals("crates.io", coordinates.getFirst().ecosystem());
    }

    @Test
    @DisplayName("a poetry.lock reads the same way, against the PyPI ecosystem")
    void readsPoetryLock() {
        String lock = """
                [[package]]
                name = "certifi"
                version = "2024.2.2"
                description = "Python package for providing Mozilla's CA Bundle."
                optional = false
                python-versions = ">=3.6"

                [[package]]
                name = "requests"
                version = "2.31.0"
                description = "Python HTTP for Humans."
                optional = false
                """;

        List<PackageCoordinate> coordinates = TomlPackageTable.parse(lock, PackageCoordinate.PYPI);

        assertEquals(List.of("certifi@2024.2.2", "requests@2.31.0"),
                coordinates.stream().map(PackageCoordinate::display).toList());
        assertEquals("PyPI", coordinates.getFirst().ecosystem());
    }

    @Test
    @DisplayName("a dependency listed inside another package's table is not invented as a package")
    void doesNotScrapeNestedNames() {
        String lock = """
                [[package]]
                name = "app"
                version = "1.0.0"
                dependencies = [
                 { name = "never-resolved" },
                ]
                """;

        List<PackageCoordinate> coordinates = TomlPackageTable.parse(lock, PackageCoordinate.CRATES_IO);

        assertEquals(List.of("app@1.0.0"), coordinates.stream().map(PackageCoordinate::display).toList());
    }

    @Test
    @DisplayName("a table without both keys is skipped rather than guessed at")
    void skipsIncompleteTables() {
        String lock = """
                [[package]]
                name = "no-version"

                [[package]]
                version = "1.0.0"

                [[package]]
                name = "complete"
                version = "2.0.0"
                """;

        assertEquals(List.of("complete@2.0.0"),
                TomlPackageTable.parse(lock, PackageCoordinate.CRATES_IO).stream()
                        .map(PackageCoordinate::display).toList());
    }

    @Test
    @DisplayName("the same crate resolved twice appears once per resolved version")
    void keepsBothResolvedVersionsOfOneCrate() {
        String lock = """
                [[package]]
                name = "libc"
                version = "0.1.0"

                [[package]]
                name = "libc"
                version = "0.2.0"
                """;

        assertEquals(List.of("libc@0.1.0", "libc@0.2.0"),
                TomlPackageTable.parse(lock, PackageCoordinate.CRATES_IO).stream()
                        .map(PackageCoordinate::display).toList());
    }

    @Test
    @DisplayName("an empty or absent lock file declares nothing")
    void handlesEmptyInput() {
        assertTrue(TomlPackageTable.parse("", PackageCoordinate.CRATES_IO).isEmpty());
        assertTrue(TomlPackageTable.parse(null, PackageCoordinate.CRATES_IO).isEmpty());
        assertTrue(TomlPackageTable.parse("[package]\nname = \"x\"\n", PackageCoordinate.CRATES_IO).isEmpty());
    }
}
