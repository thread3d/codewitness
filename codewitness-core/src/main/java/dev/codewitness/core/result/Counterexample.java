package dev.codewitness.core.result;

import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * A concrete, reproducible input that makes an implementation violate a requirement.
 *
 * <p>This is the most valuable output CodeWitness can produce. A counterexample is only recorded
 * when the failure was <em>observed by execution</em>, never when it was merely suggested.
 *
 * @param id                  counterexample identifier, for example {@code CE-001}
 * @param requirementId       violated requirement
 * @param obligationId        obligation whose experiment exposed the violation
 * @param summary             one line description
 * @param inputs              ordered input values; the exact data needed to reproduce
 * @param expected            what the requirement demands
 * @param actual              what was observed
 * @param invariantViolated   the invariant that the observation contradicts
 * @param observedBy          test or experiment that observed the violation
 * @param evidenceId          evidence record holding the raw observation
 * @param seed                random seed used, when the search was randomised
 * @param reproduction        how to reproduce the failure
 * @param discoveredBy        how the counterexample was found
 */
public record Counterexample(
        String id,
        String requirementId,
        String obligationId,
        String summary,
        Map<String, Object> inputs,
        String expected,
        String actual,
        String invariantViolated,
        String observedBy,
        String evidenceId,
        Long seed,
        ReproductionRecipe reproduction,
        DiscoveryMethod discoveredBy) {

    public Counterexample {
        Objects.requireNonNull(id, "id");
        inputs = java.util.Collections.unmodifiableMap(new LinkedHashMap<>(inputs == null ? Map.of() : inputs));
    }

    /** How a counterexample was discovered. Generated suggestions only count once executed. */
    public enum DiscoveryMethod {
        /** An existing test in the project failed. */
        EXISTING_TEST,
        /** A test generated by CodeWitness failed. */
        GENERATED_TEST,
        /** A property or fuzz search found a failing input. */
        PROPERTY_SEARCH,
        /** Static analysis demonstrated the defect directly. */
        STATIC_ANALYSIS,
        /** A language model suggested it and an independent execution confirmed it. */
        LLM_SUGGESTION_EXECUTED
    }

    /** Everything needed to run the failing scenario again, unchanged. */
    public record ReproductionRecipe(
            String description,
            List<String> command,
            Path testArtifact,
            Long seed,
            Map<String, String> properties) {

        public ReproductionRecipe {
            command = List.copyOf(command == null ? List.of() : command);
            properties = Map.copyOf(new LinkedHashMap<>(properties == null ? Map.of() : properties));
        }

        public String displayCommand() {
            return String.join(" ", command);
        }
    }
}
