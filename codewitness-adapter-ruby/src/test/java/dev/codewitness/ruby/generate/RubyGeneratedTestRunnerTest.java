package dev.codewitness.ruby.generate;

import dev.codewitness.core.exec.ExecutionSandbox;
import dev.codewitness.core.exec.IsolationLevel;
import dev.codewitness.core.exec.ProcessResult;
import dev.codewitness.core.exec.ProcessRunner;
import dev.codewitness.core.exec.ProcessSpec;
import dev.codewitness.core.model.LanguageId;
import dev.codewitness.core.model.ProjectInfo;
import dev.codewitness.core.model.ProjectRef;
import dev.codewitness.core.spi.GeneratedTest;
import dev.codewitness.core.spi.GeneratedTestExecution;
import dev.codewitness.core.spi.VerificationContext;
import dev.codewitness.ruby.RubyInterpreter;
import dev.codewitness.ruby.RubyTestContexts;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The generated-test executor's contract for the outcomes that do not need a real RSpec.
 *
 * <p>The process runner is substituted, so these tests drive the write-and-parse half of
 * {@link RubyGeneratedTestRunner#execute}: the spec must be written where RSpec's own file pattern finds
 * it, a report that carries no case or names no generated test must be reported as not executed rather
 * than as a pass, and the replay command must be a real {@code rspec} invocation carrying the seed and
 * the case index. Nothing here requires Ruby, Bundler or RSpec to be installed: the report is synthetic
 * and the binstub that makes RSpec resolvable is an empty file.
 */
class RubyGeneratedTestRunnerTest {

    /** The source the fake generator produced; the executor is what has to put it on disk. */
    private static final String SOURCE = """
            # Generated by CodeWitness TEST for run CW-2026-01-01-TEST0.
            require 'spec_helper'

            RSpec.describe 'spec.generated.cw_sc_SC_ROLLING_spec' do
            end
            """;

    @Test
    @DisplayName("the executor names itself and claims only Ruby projects")
    void namesItself(@TempDir Path root) {
        RubyGeneratedTestRunner runner = new RubyGeneratedTestRunner();

        assertEquals("rspec-generated", runner.id());
        assertTrue(runner.supports(RubyTestContexts.projectInfo(root)));

        assertFalse(runner.supports(ProjectInfo.builder(ProjectRef.of(root))
                        .language(LanguageId.JAVA)
                        .build()),
                "a Java project's generated tests are the Java adapter's to run");
    }

    @Test
    @DisplayName("an empty batch is reported as not executed, never as a pass")
    void emptyBatchIsNotExecuted(@TempDir Path root, @TempDir Path run) {
        writeProject(root);
        VerificationContext context = context(root, run, refusingToRun());

        GeneratedTestExecution execution = new RubyGeneratedTestRunner().execute(context, List.of());

        assertFalse(execution.result().executed(), execution.result().describe());
        assertEquals("no tests to run", execution.note());
        assertEquals(List.of(), execution.artifacts());
    }

    @Test
    @DisplayName("the generated spec is written into the project's test tree and left there for replay")
    void writesTheGeneratedSpecIntoTheProjectTestTree(@TempDir Path root, @TempDir Path run) throws IOException {
        String report = """
                {"examples":[{"description":"cw_case0000","full_description":"cw_case0000","status":"passed","file_path":"spec/generated/cw_sc_SC_ROLLING_spec.rb","run_time":0.01}],"summary":{"duration":0.01,"example_count":1,"failure_count":0,"pending_count":0,"errors_outside_of_examples_count":0}}
                """;

        GeneratedTestExecution execution = execute(root, run, report);

        assertTrue(execution.result().executed(), execution.note());
        assertEquals(1, execution.result().total());
        assertEquals(1, execution.result().passed());

        Path written = root.resolve("spec").resolve("generated").resolve("cw_sc_SC_ROLLING_spec.rb");
        assertTrue(Files.isRegularFile(written),
                "the spec is left in the project's own test tree: RSpec only collects a spec it finds "
                        + "there, and the counterexample's replay command is a real rspec run over this file");
        assertEquals(SOURCE, Files.readString(written, StandardCharsets.UTF_8),
                "the file RSpec ran is the file the generator produced");
        assertEquals(1, execution.artifacts().size(), execution.artifacts().toString());
        assertTrue(execution.artifacts().getFirst().endsWith("generated-tests/cw_sc_SC_ROLLING_spec.rb"),
                "the run keeps its own copy so the evidence names the executed source: " + execution.artifacts());
    }

    @Test
    @DisplayName("the batch's report is parsed by the Ruby test report parser, counterexample line and all")
    void parsesTheBatchesReportWithTheRubyTestReportParser(@TempDir Path root, @TempDir Path run) throws IOException {
        String report = """
                {"examples":[{"description":"cw_random_search","full_description":"cw_random_search","status":"failed","file_path":"spec/generated/cw_sc_SC_ROLLING_spec.rb","run_time":0.02,"exception":{"class":"RSpec::Expectations::ExpectationNotMetError","message":"CODEWITNESS_COUNTEREXAMPLE|case=3|seed=42|inputs={amount=1400}","backtrace":["/project/spec/generated/cw_sc_SC_ROLLING_spec.rb:9:in `block'"]}}],"summary":{"duration":0.02,"example_count":1,"failure_count":1,"pending_count":0,"errors_outside_of_examples_count":0}}
                """;

        GeneratedTestExecution execution = execute(root, run, report);

        assertTrue(execution.result().executed(), execution.note());
        assertEquals(1, execution.result().total());
        assertEquals(1, execution.result().failed());
        assertEquals("spec.generated.cw_sc_SC_ROLLING_spec", execution.result().cases().getFirst().suite(),
                "the report's file_path is turned into the same dotted name the generated test records, "
                        + "which is what lets the engine attribute the result");
        assertTrue(execution.result().cases().getFirst().failureMessage().contains("CODEWITNESS_COUNTEREXAMPLE"),
                "without the message the engine's counterexample would say only 'test failed'");
    }

    @Test
    @DisplayName("a report that names no generated test refuses the whole batch instead of scoring silence")
    void refusesAReportThatNamesNoGeneratedTest(@TempDir Path root, @TempDir Path run) throws IOException {
        String report = """
                {"examples":[{"description":"some other spec","full_description":"some other spec","status":"passed","file_path":"spec/ledger_spec.rb","run_time":0.01}],"summary":{"duration":0.01,"example_count":1,"failure_count":0,"pending_count":0,"errors_outside_of_examples_count":0}}
                """;

        GeneratedTestExecution execution = execute(root, run, report);

        assertFalse(execution.result().executed(), execution.result().describe());
        assertTrue(execution.note().contains("named no generated test"),
                "a report whose names are all different is one nothing can be learned from: " + execution.note());
        assertTrue(execution.note().contains("spec.ledger_spec"),
                "the note says what the report did name: " + execution.note());
        assertEquals(List.of(), execution.result().cases(),
                "no case may be handed to the engine when none could be attributed");
    }

    @Test
    @DisplayName("a report with no example is not executed, never a clean pass")
    void aReportWithNoExampleIsNotExecuted(@TempDir Path root, @TempDir Path run) throws IOException {
        GeneratedTestExecution execution = execute(root, run, "{\"examples\":[]}");

        assertFalse(execution.result().executed(), execution.result().describe());
        assertTrue(execution.note().contains("carried no example"), execution.note());
    }

    @Test
    @DisplayName("a report that never appeared is not executed, never a suite with no failures")
    void aReportThatNeverAppearedIsNotExecuted(@TempDir Path root, @TempDir Path run) throws IOException {
        writeProject(root);
        VerificationContext context = context(root, run, sandboxWritingNothing());

        GeneratedTestExecution execution =
                new RubyGeneratedTestRunner().execute(context, List.of(generatedTest()));

        assertFalse(execution.result().executed(), execution.result().describe());
        assertTrue(execution.note().contains("produced no JSON report"), execution.note());
    }

    @Test
    @DisplayName("the replay command is a real RSpec invocation carrying the seed and the case, with no invented flags")
    void reproductionCommandIsAnRSpecInvocation(@TempDir Path root, @TempDir Path run) {
        writeProject(root);
        VerificationContext context = context(root, run, refusingToRun());

        List<String> command = new RubyGeneratedTestRunner()
                .reproductionCommand(context, List.of(generatedTest()), 42L, 0);
        String rendered = String.join(" ", command);

        assertEquals("env", command.getFirst(),
                "the values travel in the environment, as in every adapter: " + rendered);
        assertTrue(command.contains("CODEWITNESS_SEED=42"), rendered);
        assertTrue(command.contains("CODEWITNESS_CASE=0"), rendered);
        assertTrue(rendered.contains("rspec"), "the command must actually run the runner: " + rendered);
        assertTrue(command.stream().anyMatch(part -> part.endsWith("cw_sc_SC_ROLLING_spec.rb")),
                "the generated spec is the file the replay runs: " + rendered);
        assertFalse(rendered.contains("--format"),
                "RSpec's formatter is how results are read, not how a failure is reproduced: " + rendered);
        assertFalse(rendered.contains("--example"),
                "--example selects by description and all the engine hands over is an index: " + rendered);
        assertFalse(rendered.contains("--seed"),
                "RSpec's --seed orders its own example sequence and would not pin the case a "
                        + "counterexample names: " + rendered);
        assertFalse(rendered.contains("--filter"),
                "PHPUnit has a --filter; RSpec does not, and inventing it would make the command a lie: "
                        + rendered);

        assertEquals(List.of(), new RubyGeneratedTestRunner().reproductionCommand(context, List.of(), null, null));
    }

    // ------------------------------------------------------------------ helpers

    /** Writes the test tree and the binstub that make RSpec resolvable without a real installation. */
    private static void writeProject(Path root) {
        try {
            RubyTestContexts.write(root, "spec/spec_helper.rb", "# the project's own helper\n");
            RubyTestContexts.write(root, "bin/rspec", "#!/usr/bin/env ruby\n");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static VerificationContext context(Path root, Path run, ExecutionSandbox sandbox) {
        return RubyTestContexts.context(
                RubyTestContexts.withAttributes(root,
                        Map.of(RubyInterpreter.ATTR_RUBY, RubyTestContexts.MISSING_RUBY)),
                run, List.of(), sandbox);
    }

    /** Runs the executor against the report the substituted RSpec is about to write. */
    private static GeneratedTestExecution execute(Path root, Path run, String reportJson) throws IOException {
        writeProject(root);
        VerificationContext context = context(root, run, sandboxWritingReport(run, reportJson));
        return new RubyGeneratedTestRunner().execute(context, List.of(generatedTest()));
    }

    /** A test whose recorded name is the dotted path its report will carry. */
    private static GeneratedTest generatedTest() {
        return new GeneratedTest("spec.generated.cw_sc_SC_ROLLING_spec", SOURCE, "cw_random_search",
                List.of("R-001"), List.of("OB-001"), "scenario", 42L, null, true);
    }

    /**
     * @return a sandbox whose process runner writes {@code reportJson} where the executor looks for the
     *     JSON report of the generated specs
     */
    private static ExecutionSandbox sandboxWritingReport(Path runDirectory, String reportJson) {
        Path report = runDirectory.resolve("artifacts").resolve("ruby").resolve("generated-rspec.json");
        return new ExecutionSandbox() {
            @Override
            public String id() {
                return "test-sandbox";
            }

            @Override
            public IsolationLevel isolationLevel() {
                return IsolationLevel.NONE;
            }

            @Override
            public String description() {
                return "test double: writes the report the runner expects without starting RSpec";
            }

            @Override
            public boolean permits(Path path) {
                return true;
            }

            @Override
            public ProcessRunner runner() {
                return spec -> {
                    try {
                        Files.createDirectories(report.getParent());
                        Files.writeString(report, reportJson, StandardCharsets.UTF_8);
                    } catch (IOException e) {
                        throw new UncheckedIOException(e);
                    }
                    return successful(spec);
                };
            }
        };
    }

    /** @return a sandbox whose runner reports a clean, empty run and writes no report at all. */
    private static ExecutionSandbox sandboxWritingNothing() {
        return new ExecutionSandbox() {
            @Override
            public String id() {
                return "test-sandbox";
            }

            @Override
            public IsolationLevel isolationLevel() {
                return IsolationLevel.NONE;
            }

            @Override
            public String description() {
                return "test double: an RSpec that ran and wrote nothing";
            }

            @Override
            public boolean permits(Path path) {
                return true;
            }

            @Override
            public ProcessRunner runner() {
                return RubyGeneratedTestRunnerTest::successful;
            }
        };
    }

    /** A sandbox whose runner fails the test if anything is executed. */
    private static ExecutionSandbox refusingToRun() {
        return new ExecutionSandbox() {
            @Override
            public String id() {
                return "test-sandbox";
            }

            @Override
            public IsolationLevel isolationLevel() {
                return IsolationLevel.NONE;
            }

            @Override
            public String description() {
                return "test double: no process may run on this path";
            }

            @Override
            public boolean permits(Path path) {
                return true;
            }

            @Override
            public ProcessRunner runner() {
                return spec -> {
                    throw new AssertionError("no process may run: " + spec.command());
                };
            }
        };
    }

    private static ProcessResult successful(ProcessSpec spec) {
        return new ProcessResult(spec.command(), spec.workingDirectory(), true, 0, "", "",
                Duration.ZERO, false, null);
    }
}
