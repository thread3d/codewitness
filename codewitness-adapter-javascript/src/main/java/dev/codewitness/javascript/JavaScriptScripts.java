package dev.codewitness.javascript;

import dev.codewitness.core.spi.VerificationContext;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes the small Node helper scripts the adapter runs inside the project.
 *
 * <p>The scripts live in the run's artefact store rather than in the project, so nothing is written
 * into the sources under verification and a reader can open the exact script that produced a
 * diagnostic. They use only Node's own modules, so a project needs no dependencies to be checked.
 */
public final class JavaScriptScripts {

    private JavaScriptScripts() {
    }

    /** Paths to the scripts written for one run. */
    public record Scripts(Path buildCheck) {
    }

    /** Writes the helper scripts into the run's artefact directory. */
    public static Scripts write(VerificationContext context) {
        Path directory = context.artifacts().artifactsDirectory().resolve("javascript/scripts");
        try {
            Files.createDirectories(directory);
            Path buildCheck = directory.resolve("build-check.mjs");
            Files.writeString(buildCheck, BUILD_CHECK, StandardCharsets.UTF_8);
            return new Scripts(buildCheck);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot write the JavaScript build helper script", e);
        }
    }

    /**
     * Syntax-checks every JavaScript file with {@code node --check}, which is the same parser that will
     * execute it. The helper walks the roots it is given, or checks a single file, and uses the runtime
     * itself rather than a third-party parser so the build cannot disagree with execution.
     *
     * <p>{@code node --check} applies Node's own module detection, so a {@code .mjs} file is parsed as a
     * module, a {@code .cjs} file as a script, and a {@code .js} file according to its nearest
     * {@code package.json} {@code type} field (or its syntax). Files the runtime cannot execute
     * unchanged, such as {@code .jsx}, are counted and reported rather than silently treated as valid.
     */
    static final String BUILD_CHECK = """
            // Generated by CodeWitness. Syntax-checks JavaScript with the runtime's own parser.
            import fs from "node:fs";
            import path from "node:path";
            import { spawnSync } from "node:child_process";

            const CHECKED = new Set([".js", ".mjs", ".cjs"]);
            const SKIPPED = new Set([".jsx"]);
            const EXCLUDED = new Set([
              "node_modules", "dist", "build", "out", "coverage", ".git", ".codewitness", ".next",
              ".nuxt", ".cache", "vendor", ".yarn", ".pnpm-store",
            ]);

            function collect(target) {
              const result = [];
              let stat;
              try {
                stat = fs.statSync(target);
              } catch {
                return result;
              }
              if (stat.isFile()) {
                if (CHECKED.has(path.extname(target)) || SKIPPED.has(path.extname(target))) result.push(target);
                return result;
              }
              if (!stat.isDirectory() || EXCLUDED.has(path.basename(target))) return result;
              let entries;
              try {
                entries = fs.readdirSync(target, { withFileTypes: true });
              } catch {
                return result;
              }
              for (const entry of entries) {
                const full = path.join(target, entry.name);
                if (entry.isDirectory()) result.push(...collect(full));
                else if (entry.isFile() && (CHECKED.has(path.extname(entry.name)) || SKIPPED.has(path.extname(entry.name)))) {
                  result.push(full);
                }
              }
              return result;
            }

            function emit(severity, file, line, column, message) {
              const text = String(message).replace(/\\\\/g, "/").replace(/\\s+/g, " ").trim();
              process.stdout.write(`CWDIAG|${severity}|${file}|${line}|${column}|${text}\\n`);
            }

            function diagnose(fallbackFile, stderr) {
              const text = String(stderr ?? "");
              const located = /^(.+?):(\\d+)\\s*$/m.exec(text);
              const summary = /^([A-Za-z]*Error):\\s*(.*)$/m.exec(text);
              return {
                file: located ? located[1] : fallbackFile,
                line: located ? located[2] : "0",
                message: summary ? `${summary[1]}: ${summary[2]}` : text.split("\\n")[0],
              };
            }

            let checked = 0;
            let failed = 0;
            let skipped = 0;
            for (const root of process.argv.slice(2)) {
              for (const file of collect(root)) {
                if (!CHECKED.has(path.extname(file))) {
                  skipped += 1;
                  continue;
                }
                checked += 1;
                const result = spawnSync(process.execPath, ["--check", file], { encoding: "utf8" });
                if (result.status !== 0) {
                  failed += 1;
                  const found = diagnose(file, result.stderr);
                  emit("ERROR", found.file, found.line, 0, found.message);
                }
              }
            }
            process.stdout.write(`CWSYNTAX|checked ${checked} file(s), ${failed} failed, ${skipped} skipped\\n`);
            if (failed > 0) process.exitCode = 1;
            """;
}
